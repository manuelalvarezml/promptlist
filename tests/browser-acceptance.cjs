// Run against the explicitly started Rust browser_fixture, never the real account.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || 'chrome'});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8788/');
  assert.equal(await page.getByRole('button',{name:'Build preview'}).isDisabled(),true);
  await page.screenshot({path:'/tmp/promptlist-disconnected.png',fullPage:true});
  await context.addCookies([{name:'promptlist_session',value:'fixture',url:'http://127.0.0.1:8788',httpOnly:true,sameSite:'Lax'}]);
  await page.reload();
  assert.equal(await page.locator('select[name=explicit],input[name=ai],input[name=external]').count(),0);
  assert.equal(await page.locator('input[name=limit]').isVisible(),false);
  assert.equal(await page.locator('select[name=source]').isVisible(),false);
  await page.getByText('+ advanced config',{exact:true}).click();
  assert.equal(await page.locator('input[name=limit]').isVisible(),true);
  await page.getByText('+ advanced config',{exact:true}).click();
  await page.locator('textarea[name=prompt]').fill('5 tracks');
  await page.locator('input[name=name]').fill('Evening selection');
  await page.getByRole('button',{name:'Build preview'}).click();
  await page.locator('.track-row').first().waitFor({timeout:15000});
  assert.equal(await page.locator('.track-row').count(),5);
  await page.getByRole('button',{name:'Move track down',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelector('.track-row')?.textContent.includes('Soft Signal'));
  assert.match(await page.locator('.track-row').first().innerText(),/Soft Signal/);
  await page.getByRole('button',{name:'Remove track',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelectorAll('.track-row').length===4);
  assert.equal(await page.locator('.track-row').count(),4);
  await page.screenshot({path:'/tmp/promptlist-composer-closed.png',fullPage:true});
  for(const width of [1440,390,320]) {
    await page.setViewportSize({width,height:900});
    await page.locator('.criteria-summary').evaluate(el=>el.open=true);
    await page.locator('.composer details').evaluate(el=>el.open=true);
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    assert.equal(await page.locator('body > header').count(),1);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`overflow at ${width}`);
    const bad=await page.locator('input,select,textarea,button').evaluateAll(nodes=>nodes.filter(n=>n.getBoundingClientRect().width>0 && (n.getBoundingClientRect().right>innerWidth+1 || n.getBoundingClientRect().left<0)).length);
    assert.equal(bad,0,`controls outside viewport at ${width}`);
    await page.screenshot({path:`/tmp/promptlist-${width}.png`,fullPage:true});
    await page.screenshot({path:`/tmp/promptlist-viewport-${width}.png`});
    await page.getByRole('button',{name:'Account menu',exact:true}).click();
    assert.equal(await page.locator('#account-menu').isVisible(),true);
    const menu=await page.locator('#account-menu').boundingBox();
    assert(menu.x>=0 && menu.x+menu.width<=width+1,`account menu overflow at ${width}`);
    await page.screenshot({path:`/tmp/promptlist-menu-${width}.png`,fullPage:true});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#account-menu').isVisible(),false);
  }
  assert.equal(await page.locator('form[action="/publish"] input[type=checkbox]').count(),0);
  let failedWrites=0;
  await page.route('**/publish',route=>{failedWrites++;return route.abort('failed');});
  await page.getByRole('button',{name:'Export to Spotify',exact:true}).click();
  await page.waitForTimeout(2500);
  assert.equal(failedWrites,1,'network failure must not automatically retry an export');
  await page.unroute('**/publish');
  await page.getByRole('button',{name:'Export to Spotify',exact:true}).click();
  await page.getByRole('link',{name:'Open in Spotify',exact:true}).waitFor({timeout:15000});
  await page.reload();
  assert.equal(await page.getByRole('link',{name:'Open in Spotify',exact:true}).count(),1);
  await page.getByRole('link',{name:'History',exact:true}).click();
  assert.equal(await page.locator('.history-entry').count(),1);
  assert.match(await page.locator('.history-entry').innerText(),/exported/i);
  await page.getByText('Original result / 5',{exact:true}).click();
  await page.getByText('Latest result / 4',{exact:true}).click();
  for(const width of [1440,390,320]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`history overflow ${width}`);
    assert.equal(await page.locator('body > header').count(),1);
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    await page.screenshot({path:`/tmp/promptlist-history-viewport-${width}.png`});
    await page.screenshot({path:`/tmp/promptlist-history-${width}.png`,fullPage:true});
  }
  await page.getByRole('button',{name:'Use prompt again',exact:true}).click();
  await page.locator('textarea[name=prompt]').waitFor();
  assert.equal(await page.locator('textarea[name=prompt]').inputValue(),'5 tracks');
  await page.locator('textarea[name=prompt]').fill('weird kinda energetic music to dedicate to a girl you love');
  await page.getByRole('button',{name:'Build preview',exact:true}).click();
  await page.waitForFunction(()=>document.body.textContent.includes('Best-effort selection:'),{},{timeout:30000});
  assert((await page.locator('.track-row').count())>0);
  await page.screenshot({path:'/tmp/promptlist-soft-preview-320.png',fullPage:true});
  await page.getByRole('link',{name:'History',exact:true}).click();
  assert.equal(await page.locator('.history-entry').count(),2);
  assert.match(await page.locator('.history-entry').first().innerText(),/weird kinda energetic/);
  await page.goto('http://127.0.0.1:8788/');
  await page.locator('textarea[name=prompt]').fill('metal; track tags only');
  let navigations=0;
  page.on('framenavigated', frame=>{if(frame===page.mainFrame()) navigations++;});
  await page.getByRole('button',{name:'Build preview',exact:true}).click();
  await page.locator('#job-status[data-running=true] progress').waitFor();
  await page.locator('input[name=name]').fill('Keep my edits while matching');
  await page.locator('textarea[name=prompt]').evaluate(el=>el.dataset.stabilityProbe='same-node');
  await page.waitForTimeout(1300);
  assert.equal(await page.locator('textarea[name=prompt]').getAttribute('data-stability-probe'),'same-node');
  await page.screenshot({path:'/tmp/promptlist-progress-320.png',fullPage:true});
  await page.locator('#job-status[data-running=false]').waitFor({timeout:30000});
  assert.equal(navigations,0,'build progress and completion must not navigate');
  assert.equal(await page.locator('input[name=name]').inputValue(),'Keep my edits while matching');
  assert((await page.locator('.track-row').count())>0);
  await page.locator('textarea[name=prompt]').fill('12 tracks');
  await page.getByRole('button',{name:'Build preview',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.track-row').length===12);
  const queue=page.getByRole('region',{name:'Playlist tracks',exact:true});
  assert.equal(await queue.evaluate(el=>el.scrollHeight>el.clientHeight),true,'long queue scrolls');
  assert.equal(navigations,0,'subsequent builds must not navigate');
  await page.screenshot({path:'/tmp/promptlist-queue-320.png',fullPage:true});
  for(const tab of ['library','sources','coverage']) {
    await page.goto(`http://127.0.0.1:8788/?tab=${tab}`);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`overflow ${tab}`);
  }
  assert.equal(await page.locator('select[name=limit]').inputValue(),'0');
  await page.goto('http://127.0.0.1:8788/?tab=library');
  await page.locator('.track-details summary').first().click();
  assert.match(await page.locator('.track-details').first().innerText(),/ISRC/);
  await page.screenshot({path:'/tmp/promptlist-library-320.png',fullPage:true});
  await page.getByRole('link',{name:/Excluded sources \/ view/}).click();
  await page.waitForURL('**/?tab=sources&excluded=true');
  assert.match(await page.locator('tbody').innerText(),/Unavailable test playlist/);
  assert.match(await page.locator('tbody').innerText(),/403/);
  assert.equal(await page.locator('tbody tr').count(),1);
  await page.screenshot({path:'/tmp/promptlist-excluded-320.png',fullPage:true});
  await page.getByRole('button',{name:'Account menu',exact:true}).click();
  await page.getByRole('link',{name:'Settings & privacy',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:/music matching/i}).count(),0);
  await page.locator('#delete-data summary').click();
  assert.equal(await page.locator('#delete-data input[name=consent]').isChecked(),false);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'/tmp/promptlist-settings-320.png',fullPage:true});
  await page.getByRole('button',{name:'Account menu',exact:true}).click();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByRole('button',{name:'Connect Spotify',exact:true}).waitFor();
  assert.match(await page.locator('.notice').innerText(),/retained/);
  assert.deepEqual(errors,[]);
  console.log('PASS: no-navigation progress/completion, preserved edits, scrollable queue, no automatic export retry, history/reuse, subjective fallback, controls, metadata, excluded sources, sign-out, mock export, desktop/390/320, no browser errors');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
